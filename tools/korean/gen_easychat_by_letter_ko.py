#!/usr/bin/env python3
"""한글판 롬의 간이회화 가나다 목록(자음 19묶음)을 C 헤더로 만든다.

한글판은 sEasyChatWordsByLetterPointers 자리(27칸)에 기타 1 + 자음 19
(ㄱ ㄲ ㄴ ㄷ ㄸ ㄹ ㅁ ㅂ ㅃ ㅅ ㅆ ㅇ ㅈ ㅉ ㅊ ㅋ ㅌ ㅍ ㅎ)를 넣고 나머지 7칸은 비운다.
단어 번호는 영어판과 같으므로 값을 그대로 옮긴다(-1, n은 '같은 이름 n개' 표시).

    python gen_easychat_by_letter_ko.py KOREAN.gba OUT.h
"""
import struct
import sys
from pathlib import Path

TABLE = 0x3EDDD0          # 한글판 롬의 (words, numWords) 27칸
NAMES = ['Others'] + ['Ko%02d' % i for i in range(1, 27)]
JAMO = 'ㄱ ㄲ ㄴ ㄷ ㄸ ㄹ ㅁ ㅂ ㅃ ㅅ ㅆ ㅇ ㅈ ㅉ ㅊ ㅋ ㅌ ㅍ ㅎ'.split()


def main():
    rom = Path(sys.argv[1]).read_bytes()
    out = ['/* Generated by tools/korean/gen_easychat_by_letter_ko.py from the',
           ' * Korean ROM (K260613): the words by initial consonant. */',
           '#include "easy_chat.h"', '#include "constants/easy_chat.h"', '']
    entries = []
    for i in range(27):
        ptr, n = struct.unpack_from('<Ii', rom, TABLE + i * 8)
        if n <= 0:
            entries.append((None, 0))
            continue
        assert 0x08000000 <= ptr < 0x09000000, (i, hex(ptr))
        words = struct.unpack_from('<%dH' % n, rom, ptr - 0x08000000)
        name = 'sEasyChatWordsByLetter_' + NAMES[i]
        note = 'others' if i == 0 else JAMO[i - 1] if i <= len(JAMO) else ''
        out.append('static const u16 %s[] = { // %s' % (name, note))
        for k in range(0, n, 12):
            out.append('    ' + ', '.join('0x%04X' % w for w in words[k:k + 12]) + ',')
        out.append('};')
        out.append('')
        entries.append((name, n))
    out.append('static const struct EasyChatWordsByLetter sEasyChatWordsByLetterPointers[] = {')
    for name, n in entries:
        out.append('    {.words = %s, .numWords = %d},' % (name or 'NULL', n))
    out.append('};')
    Path(sys.argv[2]).write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('groups', sum(1 for e in entries if e[1]), 'max words', max(n for _, n in entries))


if __name__ == '__main__':
    main()
