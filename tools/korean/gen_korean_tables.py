#!/usr/bin/env python3
"""Generate include/korean_text_tables.h: final-consonant classes of the 2350
KS X 1001 Hangul syllables (in the order the Korean ROM encodes them) and the
glyph codes of the particles the engine picks at run time.

Glyph code of a 2-byte character (lead, trail): ((lead - 0x35) << 8) | trail,
with idx = (lead - 0x37) * 239 + trail - 1 the KS X 1001 Hangul index.

    python gen_korean_tables.py OUT.h
"""
import sys


def ks_char(idx):
    r, c = divmod(idx, 94)
    return bytes([0xB0 + r, 0xA1 + c]).decode('euc_kr')


def glyph_code(ch):
    e = ch.encode('euc_kr')
    idx = (e[0] - 0xB0) * 94 + (e[1] - 0xA1)
    lead, trail = 0x37 + idx // 239, idx % 239 + 1
    return ((lead - 0x35) << 8) | trail


def final_class(ch):
    """0: no final consonant, 1: final consonant, 2: final ㄹ."""
    jong = (ord(ch) - 0xAC00) % 28
    if jong == 0:
        return 0
    return 2 if jong == 8 else 1


def main(out):
    classes = [final_class(ks_char(i)) for i in range(2350)]
    packed = []
    for i in range(0, 2352, 4):
        b = 0
        for k in range(4):
            if i + k < 2350:
                b |= classes[i + k] << (2 * k)
        packed.append(b)
    josa = ['은', '는', '을', '를', '이', '가', '와', '과', '으']
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/korean/gen_korean_tables.py. Do not edit.\n')
        f.write('#ifndef GUARD_KOREAN_TEXT_TABLES_H\n#define GUARD_KOREAN_TEXT_TABLES_H\n\n')
        f.write('// 2 bits per KS X 1001 syllable: 0 open, 1 final consonant, 2 final rieul\n')
        f.write('static const u8 sKoFinalClass[%d] = {\n' % len(packed))
        for i in range(0, len(packed), 16):
            f.write('    ' + ', '.join('0x%02X' % b for b in packed[i:i + 16]) + ',\n')
        f.write('};\n\n')
        names = {'은': 'EUN', '는': 'NEUN', '을': 'EUL', '를': 'REUL', '이': 'I', '가': 'GA',
                 '와': 'WA', '과': 'GWA', '으': 'EU'}
        for ch in josa:
            f.write('#define KO_GLYPH_%s 0x%04X // %s\n' % (names[ch], glyph_code(ch), ch))
        f.write('\n// KS X 1001 Hangul in Unicode, in KS order (which is also Unicode order):\n')
        f.write('// a binary search for a syllable gives its KS index.\n')
        f.write('static const u16 sKoUnicode[2350] = {\n')
        cps = [ord(ks_char(i)) for i in range(2350)]
        assert cps == sorted(cps)
        for i in range(0, 2350, 12):
            f.write('    ' + ', '.join('0x%04X' % c for c in cps[i:i + 12]) + ',\n')
        f.write('};\n')
        f.write('\n#endif // GUARD_KOREAN_TEXT_TABLES_H\n')


if __name__ == '__main__':
    main(sys.argv[1])
